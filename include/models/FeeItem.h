// 职责: 定义物业收费项目结构体 FeeItem（如物业费、保洁费），
//       由物业管理模块维护，供缴费登记与欠费统计使用。
// ============================================================================
#pragma once

#include <string>

/// 收费项目：描述一种物业收费的标准
struct FeeItem {
    std::string id;             ///< 收费项目编号（业务主键，如 F001）
    std::string name;           ///< 收费项目名称（如 基础物业服务）
    double monthlyAmount = 0.0; ///< 每月收费标准（金额）
    bool active = true;         ///< 是否启用（停用项目不再参与收费）
};
